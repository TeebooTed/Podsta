#!/usr/bin/env node
/**
 * Builds src/components/WordmarkSvg.jsx from brand/podsta-wordmark.svg.
 * Glyph coordinates are rounded to whole units: at the largest lockup (64px tall
 * for 1020 units) one unit is 0.06px, so the rounding is invisible.
 * The type is filled with currentColor so one inline SVG serves both themes.
 *
 *   node scripts/optimizeWordmark.js
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'brand/podsta-wordmark.svg'), 'utf8');

const ARITY = { M: 2, L: 2, Q: 4, V: 1, Z: 0 };

/** Absolute M/L/Q/V/Z (all the glyphs use) to rounded relative commands. */
function compact(d) {
  const tokens = d.match(/[A-Za-z]|-?\d*\.?\d+/g);
  let i = 0;
  let x = 0;
  let y = 0;
  let startX = 0;
  let startY = 0;
  let out = '';
  const num = () => Math.round(Number(tokens[i++]));
  const join = (values) => values.map((v, k) => (k && v >= 0 ? ` ${v}` : String(v))).join('');
  while (i < tokens.length) {
    const cmd = tokens[i++];
    if (!(cmd in ARITY)) throw new Error(`Unsupported path command ${cmd}`);
    do {
      if (cmd === 'Z') {
        out += 'z';
        x = startX;
        y = startY;
      } else if (cmd === 'V') {
        const ny = num();
        out += `v${ny - y}`;
        y = ny;
      } else {
        const values = Array.from({ length: ARITY[cmd] }, num);
        const rel = values.map((v, k) => v - (k % 2 ? y : x));
        out += cmd.toLowerCase() + join(rel);
        x = values.at(-2);
        y = values.at(-1);
        if (cmd === 'M') {
          startX = x;
          startY = y;
        }
      }
    } while (cmd !== 'Z' && i < tokens.length && !/[A-Za-z]/.test(tokens[i]));
  }
  return out;
}

const glyphs = [...source.matchAll(/<path transform="translate\((\d+),0\)" d="([^"]+)"/g)].map(([, x, d]) => ({
  x: Number(x),
  d: compact(d),
}));
if (glyphs.length !== 6) throw new Error(`Expected 6 glyphs, found ${glyphs.length}`);

const out = `// Generated by scripts/optimizeWordmark.js from brand/podsta-wordmark.svg. Do not edit by hand.
import { useId } from 'react';

const GLYPHS = ${JSON.stringify(glyphs)};

/** The brand lockup. The tile keeps its brand colours; the type uses currentColor. */
export default function WordmarkSvg({ className = '', title = 'Podsta' }) {
  const gradient = \`pg\${useId().replace(/:/g, '')}\`;
  return (
    <svg viewBox="0 0 4248 1020" className={className} role="img" aria-label={title}>
      <defs>
        <linearGradient id={gradient} x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" stopColor="#FF8A4C" />
          <stop offset=".55" stopColor="#FF6B57" />
          <stop offset="1" stopColor="#E8457A" />
        </linearGradient>
      </defs>
      <svg width="1020" height="1020" viewBox="0 0 512 512">
        <rect width="512" height="512" rx="120" fill={\`url(#\${gradient})\`} />
        <g transform="rotate(-18 256 256)">
          <path d="M70 256C70 170 150 150 256 150S442 170 442 256 362 362 256 362 70 342 70 256Z" fill="#FFF7EE" />
          <path d="M442 256C470 236 482 206 478 178" stroke="#3DD9A8" strokeWidth="22" strokeLinecap="round" fill="none" />
          <circle cx="150" cy="256" r="44" fill="#3DD9A8" />
          <circle cx="256" cy="256" r="62" fill="#2B1B3D" />
          <circle cx="256" cy="256" r="34" fill="#FFC547" />
          <circle cx="242" cy="241" r="10" fill="#FFF7EE" />
          <circle cx="362" cy="256" r="44" fill="#3DD9A8" />
        </g>
      </svg>
      <g fill="currentColor" transform="translate(1140 760) scale(1 -1)">
        {GLYPHS.map((g) => (
          <path key={g.x} transform={\`translate(\${g.x} 0)\`} d={g.d} />
        ))}
      </g>
    </svg>
  );
}
`;
writeFileSync(join(root, 'src/components/WordmarkSvg.jsx'), out);
console.log(`WordmarkSvg.jsx: ${Buffer.byteLength(out)} bytes (source SVG ${Buffer.byteLength(source)} bytes per theme)`);
